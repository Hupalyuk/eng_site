const getInitialLanguage = () => {
  if (typeof window === "undefined") return "ua";
  const stored = window.localStorage.getItem("appLanguage");
  if (supportedLanguages.some((language) => language.code === stored)) {
    return stored;
  }
  const browserLanguage = window.navigator.language?.toLowerCase() || "";
  return browserLanguage.startsWith("uk") ? "ua" : "en";
};

i18n.use(initReactI18next).init({
  resources,
  lng: getInitialLanguage(),
  fallbackLng: "ua",
  interpolation: {
    escapeValue: false,
  },
});

i18n.on("languageChanged", (language) => {
  if (typeof document !== "undefined") {
    document.documentElement.lang = language === "ua" ? "uk" : "en";
  }
  if (typeof window !== "undefined") {
    window.localStorage.setItem("appLanguage", language);
  }
});

if (typeof document !== "undefined") {
  document.documentElement.lang = i18n.language === "ua" ? "uk" : "en";
}

export default i18n;
